def list_experiments(results_dir: str = "../results") -> list:
    """List all completed experiments inside the results directory.

    Args:
        results_dir: Path to the results folder (relative or absolute).

    Returns:
        List of experiment folder names.
    """
    results_path = Path(results_dir)
    if not results_path.exists():
        print(f"[WARN] La cartella {results_dir} non esiste ancora.")
        return []

    # Support both direct results directory and an optional 'run/' subfolder
    search_dirs = [results_path]
    if (results_path / "run").is_dir():
        search_dirs.append(results_path / "run")

    experiments = []
    for sdir in search_dirs:
        for d in sorted(sdir.iterdir()):
            if d.is_dir() and any(d.glob("args-*.txt")):
                experiments.append(d.name)
    experiments = sorted(set(experiments))

    print(f"[model_loader] {len(experiments)} esperimenti trovati in '{results_dir}':")
    for exp in experiments:
        # Look up checkpoints in the matching directory
        for sdir in search_dirs:
            if (sdir / exp).is_dir():
                ckpt_found = list((sdir / exp / "models").glob("*.ckpt"))
                status = f"✓ {len(ckpt_found)} checkpoint" if ckpt_found else "✗ nessun checkpoint"
                print(f"  {exp:60s} [{status}]")
                break
    return experiments


def get_exp_config(exp_name: str, results_dir: str = "../results") -> Box:
    """Read the JSON configuration saved by main.py for an experiment.

    Args:
        exp_name:    Experiment name (subfolder name).
        results_dir: Results directory.

    Returns:
        Box containing all experiment arguments (as an attribute dict).

    Raises:
        FileNotFoundError: if no args-*.txt file exists.
    """
    exp_path = Path(results_dir) / exp_name
    if not exp_path.exists() and (Path(results_dir) / "run" / exp_name).exists():
        exp_path = Path(results_dir) / "run" / exp_name

    args_files = sorted(glob(str(exp_path / "args-*.txt")))

    if not args_files:
        raise FileNotFoundError(
            f"Nessun file args-*.txt trovato in {exp_path}. "
            "Il training è stato completato?"
        )

    # Pick the latest run in case of restarts
    args_file = args_files[-1]
    with open(args_file, "r") as f:
        args = Box(json.loads(f.read()))

    return args


def load_checkpoint(
    exp_name: str,
    results_dir: str = "../results",
    network: Optional[str] = None,
    task_id: int = 0,
    device: str = "cpu",
    num_pkts: Optional[int] = None,
    num_fields: Optional[int] = None,
    num_classes: Optional[int] = None,
) -> Tuple[torch.nn.Module, Box]:
    """Load a cluster checkpoint and reconstruct the model ready for inference.

    Supports both FACIL-wrapped models (inside LLL_Net with 'model.*' and 'heads.*' keys,
    with or without 'module.' prefix from CustomDataParallel) and raw backbone checkpoints,
    enforcing strict=True state dict loading.

    Args:
        exp_name:    Experiment folder name in results_dir (e.g. 'S1_R05_Transformer_bin_10pkts_seed0').
        results_dir: Path to results directory (default: '../results').
        network:     Architecture name ('Lopez17CNN', 'BiflowTransformer', 'MedDefenderTransformer').
                     If None, inferred from args-*.txt.
        task_id:     Task ID to load (default: 0 = first and only task for Stage 1).
        device:      Target device ('cpu' or 'cuda').
        num_pkts:    Number of packets. If None, read from args.
        num_fields:  Number of features per packet (if None, uses len(args.fields), default: 6).
        num_classes: Number of output classes. If None, read from args.

    Returns:
        (model, args): PyTorch model in eval mode + configuration Box.

    Raises:
        FileNotFoundError: if the folder or checkpoint is missing.
        ValueError:        if the architecture name is unknown.
    """
    from networks.network import LLL_Net

    exp_path = Path(results_dir) / exp_name
    if not exp_path.exists() and (Path(results_dir) / "run" / exp_name).exists():
        exp_path = Path(results_dir) / "run" / exp_name

    if not exp_path.exists():
        # Search candidate locations (results_dir and results_dir/run)
        search_dirs = [Path(results_dir)]
        if (Path(results_dir) / "run").is_dir():
            search_dirs.append(Path(results_dir) / "run")

        import re
        variant = ''
        if 'ceweighted' in exp_name:
            variant = '_ceweighted'
        elif 'mem2k' in exp_name:
            variant = '_mem2k'

        candidates = [exp_name]
        m = re.search(r'(S\d+)_R(\d+)_(.*?)(?:_ceweighted|_mem2k)?$', exp_name)
        if m:
            s, r, rest = m.groups()
            candidates.append(f"R{int(r):02d}{variant}_{s}_{rest}")
            candidates.append(f"R{int(r):02d}*")

        matches = []
        for sdir in search_dirs:
            for cand in candidates:
                matches.extend(d for d in sdir.glob(f"*{cand}*") if d.is_dir())
        matches = sorted(set(matches))

        if len(matches) == 1:
            exp_path = matches[0]
            exp_name = exp_path.name
            print(f"[model_loader] Esperimento risolto in '{exp_name}'")
        else:
            raise FileNotFoundError(
                f"Esperimento '{exp_name}' non trovato in '{results_dir}'"
                + (f" ({len(matches)} corrispondenze ambigue: {[m.name for m in matches]})" if matches else "")
                + f". Esperimenti disponibili:\n{list_experiments(results_dir)}"
            )

    # Load experiment configuration
    args = get_exp_config(exp_name, results_dir)

    # Resolve model parameters (from args or kwargs overrides)
    net_name = network or args.get("network", "BiflowTransformer")
    _num_pkts = num_pkts or args.get("num_pkts", 50)
    _num_classes = num_classes or args.get("nc_first_task", 13)

    if num_fields is not None:
        _num_fields = num_fields
    elif "fields" in args and args.fields:
        _num_fields = len(args.fields)
    else:
        _num_fields = 6

    # Locate checkpoint for the specified task
    models_dir = exp_path / "models"
    ckpt_pattern = str(models_dir / f"task-{task_id}.ckpt")
    ckpt_files = sorted(glob(ckpt_pattern))

    if not ckpt_files:
        # Also check alternative naming format (e.g., task0-<ts>.ckpt)
        ckpt_files = sorted(glob(str(models_dir / f"task{task_id}-*.ckpt")))
        if not ckpt_files:
            ckpt_files = sorted(glob(str(models_dir / "*.ckpt")))

    if not ckpt_files:
        raise FileNotFoundError(
            f"Nessun checkpoint trovato in {models_dir}. "
            "Verificare che il training sia completato con --save-models."
        )

    ckpt_path = ckpt_files[-1]  # newest checkpoint, consistent with get_exp_config
    print(f"[model_loader] Caricamento checkpoint: {ckpt_path}")

    # Instantiate backbone network
    NetClass = _get_network_class(net_name)
    net = NetClass(
        num_pkts=_num_pkts,
        num_fields=_num_fields,
        num_classes=_num_classes,
        out_features_size=args.get("out_features_size", 200),
        # Transformer hyperparameters (loaded from args with defaults)
        nlayers=args.get("nlayers", 2),
        nhead=args.get("nheads", 4),
        d_model=args.get("d_model", 128),
        dim_feedforward=args.get("dim_feedforward", 512),
    )

    # Load state weights
    try:
        from utils import safe_torch_load
    except ImportError:
        from src.utils import safe_torch_load
    state = safe_torch_load(ckpt_path, map_location=device)
    if isinstance(state, dict) and "model_state_dict" in state:
        state = state["model_state_dict"]
    elif isinstance(state, dict) and "state_dict" in state:
        state = state["state_dict"]

    # Strip 'module.' prefix (added by CustomDataParallel / DataParallel in multi-GPU runs)
    cleaned_state = {
        (k[7:] if k.startswith("module.") else k): v
        for k, v in state.items()
    }

    # Check if checkpoint uses LLL_Net wrapper ('model.*' or 'heads.*' keys)
    is_lll = any(k.startswith("model.") or k.startswith("heads.") for k in cleaned_state.keys())

    if is_lll:
        approach_name = args.get("approach", "scratch")
        activate_features = (approach_name != 'lucir') and (net_name != 'ShallowAutoencoder')
        model = LLL_Net(net, remove_existing_head=True, activate_features=activate_features)

        # Determine how many classification heads exist in the checkpoint
        head_indices = set()
        for k in cleaned_state.keys():
            if k.startswith("heads."):
                parts = k.split(".")
                if len(parts) > 1 and parts[1].isdigit():
                    head_indices.add(int(parts[1]))

        max_h = max(head_indices) if head_indices else 0
        model.add_head(_num_classes)
        for _ in range(1, max_h + 1):
            nc_incr = args.get("nc_incr_tasks", _num_classes)
            model.add_head(nc_incr)

        model.load_state_dict(cleaned_state, strict=True)

        # get_attention_maps is provided by LLL_Net (forwards return_attention to the backbone
        # and returns head outputs along with attention weights).
    else:
        model = net
        model.load_state_dict(cleaned_state, strict=True)

    model.to(device)
    model.eval()

    num_params = sum(p.numel() for p in model.parameters())
    print(
        f"[model_loader] [OK] Modello '{net_name}' caricato con successo "
        f"({num_params:,} parametri, fields={_num_fields}, strict=True) "
        f"su device='{device}'"
    )
    return model, args


# ---------------------------------------------------------------------------
# Helper: stratified subset for XAI evaluation (reduces sample count for speed)
# ---------------------------------------------------------------------------

def get_xai_subset(
    dataset,
    n_per_class: int = 500,
    seed: int = 42,
) -> Tuple[torch.Tensor, torch.Tensor]:
    """Extract a stratified subset from the dataset for XAI analysis.

    With 604k total flows, SHAP KernelExplainer is too slow over the full split.
    This helper samples n_per_class examples per class to keep runtime manageable
    (~30 min per explanation method).

    Args:
        dataset:     NetworkingDataset (exposes .images and .labels).
        n_per_class: Samples per class (default: 500).
        seed:        Random seed for reproducibility.

    Returns:
        (X_subset, y_subset): Tensors ready for model inference.
    """
    import numpy as np

    rng = np.random.default_rng(seed)

    images = dataset.images   # list/array of (1, T, F) arrays
    labels = dataset.labels   # list of int labels

    labels_arr = np.array(labels)
    classes = np.unique(labels_arr)

    X_list, y_list = [], []
    for cls in classes:
        idx = np.where(labels_arr == cls)[0]
        if len(idx) > n_per_class:
            idx = rng.choice(idx, size=n_per_class, replace=False)
        for i in idx:
            X_list.append(images[i])
            y_list.append(labels[i])

    # Final permutation: without shuffling, the subset stays ordered by class and any
    # downstream slice X[:N] (SHAP, LIME, IG, metrics, adversaries) would contain only one class.
    perm = rng.permutation(len(y_list))
    X = torch.tensor(np.stack(X_list)[perm], dtype=torch.float32)
    y = torch.tensor(np.asarray(y_list)[perm], dtype=torch.long)

    print(
        f"[model_loader] Subset XAI: {len(y)} campioni, "
        f"{len(classes)} classi, ~{n_per_class} per classe"
    )
    return X, y
