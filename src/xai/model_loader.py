"""
model_loader.py — Helper for Loading Cluster Training Checkpoints
=================================================================
Loads models saved by main.py inside ../results/ (following the directory layout
generated by the FACIL framework used in this project).

Expected result directory layout (generated by main.py --save-models):
    ../results/<exp_name>/models/task-t.ckpt  <- model checkpoint
    ../results/<exp_name>/args-<ts>.txt       <- JSON configuration
    ../results/<exp_name>/results/per_class_metrics-<ts>.txt

Usage:
    from model_loader import load_checkpoint, list_experiments, get_exp_config

    model, args = load_checkpoint(
        exp_name="S1_R05_Transformer_bin_10pkts_seed0",
        results_dir="../results",
        network="BiflowTransformer",
        device="cuda"
    )
"""

