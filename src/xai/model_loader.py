def _get_network_class(network_name: str):
    """Resolve an architecture name string into the corresponding PyTorch class."""
    from networks.lopez17cnn import Lopez17CNN
    from networks.transformer import BiflowTransformer, MedDefenderTransformer

    mapping = {
        "Lopez17CNN": Lopez17CNN,
        "BiflowTransformer": BiflowTransformer,
        "MedDefenderTransformer": MedDefenderTransformer,
    }
    if network_name not in mapping:
        raise ValueError(
            f"Architettura '{network_name}' non riconosciuta. "
            f"Disponibili: {list(mapping.keys())}"
        )
    return mapping[network_name]


