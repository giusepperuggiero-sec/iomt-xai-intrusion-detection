try:
    from box import Box  # type: ignore[import-untyped, import-not-found]
except ImportError:
    class Box(dict):
        def __getattr__(self, item):
            val = self.get(item)
            if isinstance(val, dict):
                return Box(val)
            return val
        def __setattr__(self, item, value):
            self[item] = value


